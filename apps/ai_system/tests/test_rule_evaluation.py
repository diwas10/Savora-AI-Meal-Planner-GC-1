@pytest.mark.parametrize("operator", list(PredicateOperator))
@pytest.mark.parametrize("value", [True, 1, ("Alpha",), ()])
def test_incompatible_categorical_shapes_never_unknown(
    operator: PredicateOperator, value: Any
) -> None:
    # Ordered categorical rule configurations are rejected at admission; other
    # operators reject supplied non-scalar categorical values, even incomplete ones.
    if operator in (
        PredicateOperator.LT,
        PredicateOperator.LE,
        PredicateOperator.GT,
        PredicateOperator.GE,
    ):
        rule = numeric_rule(operator)
        supplied = fact(
            "synthetic_quantity",
            value,
            complete=False,
            unit=MeasurementUnit.MG if type(value) is int else None,
            basis=MeasurementBasis.PER_100_G if type(value) is int else None,
            basis_source=source("synthetic-per-100-g") if type(value) is int else None,
        )
        if type(value) is int:
            assert (
                evaluate(packet((rule,), candidate_facts=(supplied,), context_facts=()))[0].status
                is RuleStatus.UNKNOWN
            )
            return
    else:
        rule = definition(
            attribute="synthetic_category",
            required_facts=("synthetic_category",),
            operator=operator,
            value=("Alpha",)
            if operator in (PredicateOperator.IN, PredicateOperator.NOT_IN)
            else "Alpha",
        )
        supplied = fact(
            "synthetic_category",
            value,
            complete=False,
            unit=MeasurementUnit.DIMENSIONLESS if type(value) is int else None,
            basis=MeasurementBasis.AS_RECORDED if type(value) is int else None,
            basis_source=source("synthetic-recorded") if type(value) is int else None,
        )
    with pytest.raises(ValidationError):
        evaluate(packet((rule,), candidate_facts=(supplied,), context_facts=()))


@pytest.mark.parametrize("bad", [float("inf"), float("-inf"), float("nan"), -1, True])
@pytest.mark.parametrize("where", ["rule", "fact"])
def test_corrupted_numeric_operands_never_hide_behind_missing_applicability(
    bad: Any, where: str
) -> None:
    inputs: list[Any] = list(
        packet((numeric_rule(),), candidate_facts=(numeric_fact(1),), context_facts=())
    )
    if where == "rule":
        inputs[0] = inputs[0].model_copy(
            update={"rules": (inputs[0].rules[0].model_copy(update={"value": bad}),)}
        )
    else:
        item = inputs[1].facts[0]
        malformed = item.model_copy(
            update={"observation": item.observation.model_copy(update={"value": bad})}
        )
        inputs[1] = inputs[1].model_copy(update={"facts": (malformed,)})
    with pytest.raises(ValidationError):
        evaluate(inputs)


