@pytest.mark.parametrize(
    "state", ["true", "false", "missing", "null", "incomplete_true", "incomplete_false"]
)
@pytest.mark.parametrize("predicate_pass", [True, False])
def test_applicability_states_do_not_remove_checks(state: str, predicate_pass: bool) -> None:
    context_facts = (
        ()
        if state == "missing"
        else (
            fact(
                "synthetic_context_enabled",
                None if state == "null" else state in ("true", "incomplete_true"),
                complete=state not in ("null", "incomplete_true", "incomplete_false"),
                subject=FactSubjectKind.CONTEXT,
            ),
        )
    )
    inputs = packet(context_facts=context_facts, candidate_facts=(fact(value=not predicate_pass),))
    manifest = build_expected_check_manifest(*inputs)
    evaluations = evaluate_rule_checks(*inputs, manifest)
    assert len(manifest.required_checks) == len(evaluations) == 1
    result = evaluations[0]
    expected_app = {
        "true": ApplicabilityStatus.APPLICABLE,
        "false": ApplicabilityStatus.NOT_APPLICABLE,
    }.get(state, ApplicabilityStatus.UNKNOWN)
    assert result.applicability is expected_app
    assert (
        result.status is (RuleStatus.PASS if predicate_pass else RuleStatus.FAIL)
        if state == "true"
        else (result.status is RuleStatus.UNKNOWN)
    )
    assert result.applicability_evidence
    trace = RuleTrace(
        candidate_id="recipe",
        context_id="context",
        manifest_id=manifest.manifest_id,
        manifest_version=manifest.manifest_version,
        required_checks=manifest.required_checks,
        evaluations=evaluations,
    )
    assert aggregate_hard_status(trace) is (
        RuleStatus.PASS
        if state == "false" or (state == "true" and predicate_pass)
        else RuleStatus.FAIL
        if state == "true"
        else RuleStatus.UNKNOWN
    )


@pytest.mark.parametrize("own,dependency", list(product((True, False, None), repeat=2)))
def test_conservative_dependency_conjunction(own: bool | None, dependency: bool | None) -> None:
    rule = definition()
    dep = descriptor("synthetic-profile-enabled")
    host = descriptor(rules=(rule,), dependencies=(dep.reference,))
    inputs = packet(
        (rule,),
        descriptors=(host, dep),
        context_facts=(
            fact(
                "synthetic_context_enabled",
                own,
                complete=own is not None,
                subject=FactSubjectKind.CONTEXT,
            ),
            fact(
                "synthetic_profile_enabled",
                dependency,
                complete=dependency is not None,
                subject=FactSubjectKind.PROFILE,
            ),
        ),
    )
    result = evaluate(inputs)[0]
    expected = (
        ApplicabilityStatus.UNKNOWN
        if own is None or dependency is None
        else ApplicabilityStatus.NOT_APPLICABLE
        if own is False or dependency is False
        else ApplicabilityStatus.APPLICABLE
    )
    assert result.applicability is expected
    assert {ref.evidence_id for ref in result.applicability_evidence} == {
        "app-synthetic-context-enabled",
        "app-synthetic-profile-enabled",
        "observation-synthetic_context_enabled",
        "observation-synthetic_profile_enabled",
    }


@pytest.mark.parametrize("reverse", [False, True])
def test_transitive_shared_dependencies_are_deterministic(reverse: bool) -> None:
    rule = definition()
    profile = descriptor("synthetic-profile-enabled")
    guard = descriptor("synthetic-context-guard", dependencies=(profile.reference,))
    host = descriptor(rules=(rule,), dependencies=(guard.reference, profile.reference))
    records = (host, guard, profile)
    facts = (
        fact("synthetic_context_enabled", True, subject=FactSubjectKind.CONTEXT),
        fact("synthetic_context_guard", True, subject=FactSubjectKind.CONTEXT),
        fact("synthetic_profile_enabled", False, subject=FactSubjectKind.PROFILE),
    )
    inputs = packet(
        (rule,),
        descriptors=tuple(reversed(records)) if reverse else records,
        context_facts=tuple(reversed(facts)) if reverse else facts,
    )
    result = evaluate(inputs)[0]
    assert result.applicability is ApplicabilityStatus.NOT_APPLICABLE
    assert len(result.applicability_evidence) == 6


