def numeric_fact(value: Any, **changes: Any) -> VersionedFact:
    return fact(
        "synthetic_quantity",
        value,
        unit=MeasurementUnit.MG,
        basis=MeasurementBasis.PER_100_G,
        basis_source=source("synthetic-per-100-g"),
        **changes,
    )


def numeric_rule(operator: PredicateOperator = PredicateOperator.LE, **changes: Any) -> Any:
    return definition(
        attribute="synthetic_quantity",
        operator=operator,
        value=7,
        unit=MeasurementUnit.MG,
        required_facts=("synthetic_quantity",),
        **changes,
    )


def evaluate(inputs: Any) -> tuple[RuleEvaluation, ...]:
    kb, candidate, context = inputs
    manifest = build_expected_check_manifest(kb, candidate, context)
    return evaluate_rule_checks(kb, candidate, context, manifest)


# Expected results are a literal independently specified truth table, not calls to
# the production comparator or generated by the same operator dispatch.
NUMERIC_TABLE = [
    (PredicateOperator.LT, (True, False, False)),
    (PredicateOperator.LE, (True, True, False)),
    (PredicateOperator.GT, (False, False, True)),
    (PredicateOperator.GE, (False, True, True)),
    (PredicateOperator.EQ, (False, True, False)),
    (PredicateOperator.NE, (True, False, True)),
]


@pytest.mark.parametrize("operator,expected", NUMERIC_TABLE)
@pytest.mark.parametrize("offset", [0, 1, 2])
@pytest.mark.parametrize("floating", [False, True])
def test_all_numeric_operator_boundaries(
    operator: PredicateOperator, expected: tuple[bool, ...], offset: int, floating: bool
) -> None:
    value = (6.0, 7.0, 8.0)[offset] if floating else (6, 7, 8)[offset]
    result = evaluate(packet((numeric_rule(operator),), candidate_facts=(numeric_fact(value),)))[0]
    assert result.status is (RuleStatus.PASS if expected[offset] else RuleStatus.FAIL)
    assert result.applicability is ApplicabilityStatus.APPLICABLE
    assert result.reason == "synthetic-rule-evaluation.v1:" + (
        "PREDICATE_TRUE" if expected[offset] else "PREDICATE_FALSE"
    )
    assert {e.evidence_id for e in result.facts[0].evidence} == {
        "observation-synthetic_quantity",
        "synthetic-per-100-g",
    }
    assert validate_contract_json(RuleEvaluation, result.model_dump_json(by_alias=True)) == result


@pytest.mark.parametrize(
    "operator,value,expected",
    [
        (PredicateOperator.IN, "Alpha", True),
        (PredicateOperator.IN, "Beta", True),
        (PredicateOperator.IN, "alpha", False),
        (PredicateOperator.IN, "", False),
        (PredicateOperator.NOT_IN, "Alpha", False),
        (PredicateOperator.NOT_IN, "Beta", False),
        (PredicateOperator.NOT_IN, "alpha", True),
        (PredicateOperator.NOT_IN, "Gamma", True),
        (PredicateOperator.EQ, "Alpha", True),
        (PredicateOperator.EQ, "alpha", False),
        (PredicateOperator.NE, "Alpha", False),
        (PredicateOperator.NE, "alpha", True),
    ],
)
def test_categorical_operators_case_sensitive(
    operator: PredicateOperator, value: str, expected: bool
) -> None:
    # Empty strings are structurally invalid, not categorical UNKNOWN/defaults.
    if value == "":
        with pytest.raises(ValidationError):
            fact("synthetic_category", value)
        return
    rule = definition(
        attribute="synthetic_category",
        required_facts=("synthetic_category",),
        operator=operator,
        value=("Alpha", "Beta")
        if operator in (PredicateOperator.IN, PredicateOperator.NOT_IN)
        else "Alpha",
    )
    result = evaluate(packet((rule,), candidate_facts=(fact("synthetic_category", value),)))[0]
    assert result.status is (RuleStatus.PASS if expected else RuleStatus.FAIL)


