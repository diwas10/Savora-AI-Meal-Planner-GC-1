"""Generate TypeScript declarations (`packages/contracts/src/openapi.d.ts`) from `openapi.json`."""

import json
import re
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[4]
OPENAPI_PATH = REPO_ROOT / "packages/contracts/openapi.json"
DTS_PATH = REPO_ROOT / "packages/contracts/src/openapi.d.ts"

_IDENT_RE = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")


def _safe_key(key: str) -> str:
    return key if _IDENT_RE.match(key) else json.dumps(key)


def _schema_to_ts(schema: Any, indent: str = "    ") -> str:
    if not isinstance(schema, dict):
        return "unknown"
    if "$ref" in schema:
        ref_name = str(schema["$ref"]).replace("#/components/schemas/", "")
        return f'components["schemas"][{json.dumps(ref_name)}]'
    if isinstance(schema.get("anyOf"), list):
        return " | ".join(_schema_to_ts(s, indent) for s in schema["anyOf"])
    if isinstance(schema.get("oneOf"), list):
        return " | ".join(_schema_to_ts(s, indent) for s in schema["oneOf"])
    if isinstance(schema.get("enum"), list):
        return " | ".join(json.dumps(v) for v in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"])

    stype = schema.get("type")
    if stype == "string":
        return "string"
    if stype in ("integer", "number"):
        return "number"
    if stype == "boolean":
        return "boolean"
    if stype == "null":
        return "null"
    if stype == "array":
        item_ts = _schema_to_ts(schema.get("items"), indent)
        return f"({item_ts})[]"
    if stype == "object":
        props = schema.get("properties") or {}
        req = set(schema.get("required") or [])
        prop_keys = list(props.keys())
        if not prop_keys:
            add_props = schema.get("additionalProperties")
            if isinstance(add_props, dict):
                return f"Record<string, {_schema_to_ts(add_props, indent)}>"
            return "Record<string, unknown>"
        lines = []
        for k in prop_keys:
            opt = "" if k in req else "?"
            lines.append(
                f"{indent}  {_safe_key(k)}{opt}: {_schema_to_ts(props[k], indent + '  ')};"
            )
        joined = "\n".join(lines)
        return f"{{\n{joined}\n{indent}}}"
    return "unknown"


def _response_schema(responses: dict[str, Any]) -> Any:
    for code in ("200", "201", "202"):
        content = responses.get(code, {}).get("content", {})
        schema = content.get("application/json", {}).get("schema")
        if schema:
            return schema
    return None


def export_contracts(
    *,
    openapi_spec: dict[str, Any],
    openapi_path: Path = OPENAPI_PATH,
    dts_path: Path = DTS_PATH,
) -> None:
    openapi_path.parent.mkdir(parents=True, exist_ok=True)
    openapi_path.write_text(json.dumps(openapi_spec, indent=2) + "\n", encoding="utf-8")

    schemas = openapi_spec.get("components", {}).get("schemas", {})
    out: list[str] = [
        "/**",
        " * AUTO-GENERATED by @savora/contracts from openapi.json.",
        " * Do not edit manually.",
        " */",
        "",
        "export interface components {",
        "  schemas: {",
    ]
    for name, schema in schemas.items():
        out.append(f"    {_safe_key(name)}: {_schema_to_ts(schema, '    ')};")
    out.append("  };")
    out.append("}")
    out.append("")
    out.append("export interface paths {")
    for path_str, methods in (openapi_spec.get("paths") or {}).items():
        out.append(f"  {json.dumps(path_str)}: {{")
        for method, op in (methods or {}).items():
            if not isinstance(op, dict):
                continue
            resp_schema = _response_schema(op.get("responses") or {})
            req_schema = (
                op.get("requestBody", {})
                .get("content", {})
                .get("application/json", {})
                .get("schema")
            )
            req_ts = _schema_to_ts(req_schema, "      ") if req_schema else "never"
            resp_ts = _schema_to_ts(resp_schema, "      ") if resp_schema else "unknown"
            out.extend(
                [
                    f"    {_safe_key(method)}: {{",
                    f"      requestBody?: {req_ts};",
                    f"      response: {resp_ts};",
                    "    };",
                ]
            )
        out.append("  };")
    out.append("}")
    out.append("")

    dts_path.parent.mkdir(parents=True, exist_ok=True)
    dts_path.write_text("\n".join(out), encoding="utf-8")
