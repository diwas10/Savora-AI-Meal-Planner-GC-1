#!/usr/bin/env node
/**
 *Deterministic OpenAPI 3.1 -> TypeScript declarations generator for @savora/contracts.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const openapiPath = resolve(__dirname, "..", "openapi.json");
const outPath = resolve(__dirname, "..", "src", "openapi.d.ts");

const spec = JSON.parse(readFileSync(openapiPath, "utf8"));
const schemas = spec?.components?.schemas ?? {};

function safeKey(key) {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) ? key : JSON.stringify(key);
}

function schemaToTs(schema, indent = "    ") {
  if (!schema || typeof schema !== "object") {
    return "unknown";
  }
  if (schema.$ref) {
    const refName = schema.$ref.replace("#/components/schemas/", "");
    return `components["schemas"][${JSON.stringify(refName)}]`;
  }
  if (Array.isArray(schema.anyOf)) {
    return schema.anyOf.map((s) => schemaToTs(s, indent)).join(" | ");
  }
  if (Array.isArray(schema.oneOf)) {
    return schema.oneOf.map((s) => schemaToTs(s, indent)).join(" | ");
  }
  if (Array.isArray(schema.enum)) {
    return schema.enum.map((v) => JSON.stringify(v)).join(" | ");
  }
  if (schema.const !== undefined) {
    return JSON.stringify(schema.const);
  }
  switch (schema.type) {
    case "string":
      return "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    case "array": {
      const itemTs = schemaToTs(schema.items, indent);
      return `(${itemTs})[]`;
    }
    case "object": {
      const props = schema.properties ?? {};
      const req = new Set(schema.required ?? []);
      const propKeys = Object.keys(props);
      if (propKeys.length === 0) {
        if (schema.additionalProperties && typeof schema.additionalProperties === "object") {
          return `Record<string, ${schemaToTs(schema.additionalProperties, indent)}>`;
        }
        return "Record<string, unknown>";
      }
      const lines = propKeys.map((k) => {
        const optional = req.has(k) ? "" : "?";
        return `${indent}  ${safeKey(k)}${optional}: ${schemaToTs(props[k], indent + "  ")};`;
      });
      return `{\n${lines.join("\n")}\n${indent}}`;
    }
    default:
      return "unknown";
  }
}

const out = [];
out.push("/**");
out.push(" * AUTO-GENERATED by @savora/contracts generate script from openapi.json.");
out.push(" * Do not edit manually.");
out.push(" */");
out.push("");
out.push("export interface components {");
out.push("  schemas: {");
for (const [name, schema] of Object.entries(schemas)) {
  out.push(`    ${safeKey(name)}: ${schemaToTs(schema, "    ")};`);
}
out.push("  };");
out.push("}");
out.push("");
out.push("export interface paths {");
for (const [pathStr, methods] of Object.entries(spec.paths ?? {})) {
  out.push(`  ${JSON.stringify(pathStr)}: {`);
  for (const [method, op] of Object.entries(methods ?? {})) {
    const resp200 =
      op?.responses?.["200"]?.content?.["application/json"]?.schema ??
      op?.responses?.["201"]?.content?.["application/json"]?.schema ??
      op?.responses?.["202"]?.content?.["application/json"]?.schema;
    const reqBody = op?.requestBody?.content?.["application/json"]?.schema;
    out.push(`    ${safeKey(method)}: {`);
    out.push(`      requestBody?: ${reqBody ? schemaToTs(reqBody, "      ") : "never"};`);
    out.push(`      response: ${resp200 ? schemaToTs(resp200, "      ") : "unknown"};`);
    out.push("    };");
  }
  out.push("  };");
}
out.push("}");
out.push("");

writeFileSync(outPath, out.join("\n"), "utf8");
